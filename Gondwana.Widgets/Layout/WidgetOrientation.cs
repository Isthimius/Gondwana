namespace Gondwana.Widgets.Layout;

/// <summary>
/// Defines the primary layout or fill direction used by widgets.
/// </summary>
public enum WidgetOrientation
{
    /// <summary>
    /// Arranges or fills content from left to right.
    /// </summary>
    Horizontal,

    /// <summary>
    /// Arranges content from top to bottom or fills progress from bottom to top.
    /// </summary>
    Vertical
}
