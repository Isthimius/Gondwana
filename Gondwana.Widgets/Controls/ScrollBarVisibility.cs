namespace Gondwana.Widgets.Controls;

/// <summary>
/// Specifies when a list box displays its vertical scrollbar.
/// </summary>
public enum ScrollBarVisibility
{
    /// <summary>Displays the scrollbar only when the items overflow the visible rows.</summary>
    Auto,

    /// <summary>Always displays the scrollbar while the list box is visible.</summary>
    Always,

    /// <summary>Never displays the scrollbar.</summary>
    Never
}
